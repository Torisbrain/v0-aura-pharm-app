function searchLocalDatabase(query: string): NAFDACProduct[] {
  const searchTerm = query.toLowerCase().trim()

  return nigerianDrugsDatabase.filter((product) => {
    return (
      product.productName.toLowerCase().includes(searchTerm) ||
      product.activeIngredients.toLowerCase().includes(searchTerm) ||
      product.nrn.toLowerCase().includes(searchTerm) ||
      product.applicantName.toLowerCase().includes(searchTerm)
    )
  })
}
