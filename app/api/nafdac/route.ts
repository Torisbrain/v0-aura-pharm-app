import { NextRequest, NextResponse } from "next/server"

// NAFDAC Greenbook search endpoint
const NAFDAC_API_URL = "https://greenbook.nafdac.gov.ng/api/products"

interface NAFDACProduct {
  productName: string
  activeIngredients: string
  productCategory: string
  nrn: string // NAFDAC Registration Number
  form: string
  roa: string // Route of Administration
  strengths: string
  applicantName: string
  approvalDate: string
  status: string
}

export async function GET(request: NextRequest) {
  const searchParams = request.nextUrl.searchParams
  const query = searchParams.get("q")

  if (!query) {
    return NextResponse.json(
      { error: "Search query is required" },
      { status: 400 }
    )
  }

  try {
    // Try to fetch from NAFDAC Greenbook API
    const response = await fetch(
      `${NAFDAC_API_URL}?search=${encodeURIComponent(query)}`,
      {
        headers: {
          Accept: "application/json",
        },
        next: { revalidate: 3600 }, // Cache for 1 hour
      }
    )

    if (response.ok) {
      const data = await response.json()
      return NextResponse.json({
        source: "nafdac",
        results: data,
      })
    }
  } catch (error) {
    console.log("[v0] NAFDAC API not available, using fallback database")
  }

  // Fallback to comprehensive local database
  const results = searchLocalDatabase(query)
  return NextResponse.json({
    source: "local",
    results,
  })
}

